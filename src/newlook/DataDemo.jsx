import React, { useMemo, useState } from 'react';
import { Link, useLocation } from 'react-router-dom';
import {
  Card,
  ConfirmDialog,
  DetailFacts,
  DetailPanel,
  FilterRow,
  ListWithDetail,
  Menu,
  PaymentChip,
  Pagination,
  Segmented,
  Skeleton,
  StatusLabel,
  SummaryRow,
  Table,
  Tabs,
  EmptyState,
  formatCount,
  formatMoney,
  useListParams,
  useToast,
} from './components';

/**
 * The data components with sample data (ticket P1-4): a list page built from Tabs, SummaryRow, FilterRow, Table,
 * Pagination and the detail panel, with 135 made-up sales. The sample data is generated by a fixed formula, never
 * copied from a shop. Every state can be shown with the "Show the list as" switch; the tab, period, search,
 * filters, page, rows per page and the open sale all live in this page's address, so a refresh or a copied link
 * opens the same view.
 */
const METHODS = ['M-Pesa', 'Cash', 'Card', 'On credit'];
const NAMES = ['Wanjiru Kamau', 'Otieno Odhiambo', 'Amina Hassan', 'Kiprop Chebet', 'Njeri Mwangi', 'Mutua Musyoka', 'Walk-in customer'];
const STATUS_CYCLE = ['paid', 'paid', 'paid', 'unpaid', 'paid', 'overdue', 'paid', 'part-returned'];

const SALES = Array.from({ length: 135 }, (_, i) => {
  const n = 135 - i;
  const status = STATUS_CYCLE[i % STATUS_CYCLE.length];
  return {
    id: String(n).padStart(4, '0'),
    customer: NAMES[i % NAMES.length],
    method: status === 'unpaid' || status === 'overdue' ? 'On credit' : METHODS[i % 3],
    amount: 350 + ((i * 937) % 9650),
    status,
    daysAgo: Math.floor(i / 4),
    time: `${String(8 + (i % 10)).padStart(2, '0')}:${String((i * 7) % 60).padStart(2, '0')}`,
  };
});

const when = (sale) => {
  if (sale.daysAgo === 0) return `Today, ${sale.time}`;
  if (sale.daysAgo === 1) return `Yesterday, ${sale.time}`;
  return `${sale.daysAgo} days ago, ${sale.time}`;
};

const PERIOD_DAYS = { today: 1, '7d': 7, '30d': 30 };
const STATUS_WORDS = [
  { value: '', label: 'All statuses' },
  { value: 'paid', label: 'Paid' },
  { value: 'unpaid', label: 'Unpaid' },
  { value: 'overdue', label: 'Overdue' },
  { value: 'part-returned', label: 'Part returned' },
];
const METHOD_OPTIONS = [{ value: '', label: 'All methods' }, ...METHODS.map((m) => ({ value: m, label: m }))];
const VIEWS = [
  { value: 'data', label: 'Data' },
  { value: 'loading', label: 'Loading' },
  { value: 'empty', label: 'Empty' },
  { value: 'error', label: 'Error' },
];
const FILTER_KEYS = ['status', 'method'];
const STATE_KEYS = ['open', 'view'];
const BASE = '/new-look/components';

const SalesDemo = () => {
  const toast = useToast();
  const [voiding, setVoiding] = useState(null);
  const location = useLocation();
  const params = useListParams({ defaultPeriod: '30d', filterKeys: FILTER_KEYS, stateKeys: STATE_KEYS });
  const { page, size, q, period, from, to, filters, state } = params;
  const tabKey = new URLSearchParams(location.search).get('tab') || 'all';
  const view = state.view || 'data';

  // Tabs are part of the address; they keep the other values out of the way by starting a fresh view
  const tabs = [
    { key: 'all', label: 'All sales', to: BASE },
    { key: 'unpaid', label: 'Unpaid', to: `${BASE}?tab=unpaid`, count: SALES.filter((s) => s.status === 'unpaid' || s.status === 'overdue').length },
    { key: 'returns', label: 'Returns', to: `${BASE}?tab=returns`, count: SALES.filter((s) => s.status === 'part-returned').length },
  ];

  const matching = useMemo(() => {
    const text = q.toLowerCase();
    return SALES.filter((s) => {
      if (tabKey === 'unpaid' && s.status !== 'unpaid' && s.status !== 'overdue') return false;
      if (tabKey === 'returns' && s.status !== 'part-returned') return false;
      if (PERIOD_DAYS[period] && s.daysAgo >= PERIOD_DAYS[period]) return false;
      if (filters.status && s.status !== filters.status) return false;
      if (filters.method && s.method !== filters.method) return false;
      if (text && !`${s.id} ${s.customer}`.toLowerCase().includes(text)) return false;
      return true;
    });
  }, [q, period, filters.status, filters.method, tabKey]);

  const shownRows = view === 'empty' ? [] : matching;
  const lastPage = Math.max(1, Math.ceil(shownRows.length / size));
  const current = Math.min(page, lastPage);
  const pageRows = shownRows.slice((current - 1) * size, current * size);
  const total = shownRows.reduce((sum, s) => sum + s.amount, 0);
  const unpaid = shownRows.filter((s) => s.status === 'unpaid' || s.status === 'overdue').reduce((sum, s) => sum + s.amount, 0);

  const open = pageRows.find((s) => s.id === state.open);
  const openIndex = open ? pageRows.indexOf(open) : -1;
  const openSale = (id) => params.set({ open: id, page: current });

  const columns = [
    { key: 'id', header: 'Sale', nowrap: true, render: (s) => <strong>{s.id}</strong> },
    { key: 'date', header: 'Date', render: (s) => when(s) },
    { key: 'customer', header: 'Customer' },
    { key: 'method', header: 'Method', render: (s) => <PaymentChip method={s.method} /> },
    { key: 'status', header: 'Status', render: (s) => <StatusLabel status={s.status} /> },
    { key: 'amount', header: 'Amount', money: true, nowrap: true },
    {
      key: 'actions',
      header: <span className="nl-visually-hidden">Actions</span>,
      render: (s) => (
        <Menu
          label={`More actions for sale ${s.id}`}
          items={[
            { label: 'Open details', onClick: () => openSale(s.id) },
            { label: 'Print receipt', onClick: () => toast.success(`Receipt for sale ${s.id} sent to the printer (demo)`) },
            { label: 'Void sale', destructive: true, onClick: () => setVoiding(s) },
          ]}
        />
      ),
    },
  ];

  const emptyState = params.hasFilters || tabKey !== 'all'
    ? { icon: 'search', title: 'No sales match', description: 'Try a wider period or clear the filters.', action: { label: 'Clear filters', onClick: params.clear } }
    : { title: 'No sales yet', description: 'Sales appear here as soon as you make one.', action: { label: 'Make a sale', icon: 'plus', onClick: () => {} } };

  const list = (
    <div style={{ display: 'grid', gap: 'var(--card-gap)' }}>
      <SummaryRow
        loading={view === 'loading'}
        items={[
          { label: 'Total sales', value: formatMoney(total), note: formatCount(shownRows.length, 'sale') },
          { label: 'Received', value: formatMoney(total - unpaid) },
          { label: 'Unpaid', value: formatMoney(unpaid) },
        ]}
      />
      <FilterRow
        period={period}
        onPeriod={(value) => params.set({ period: value })}
        from={from}
        to={to}
        onRange={(range) => params.set(range)}
        search={q}
        onSearch={(value) => params.set({ q: value })}
        searchLabel="Search sales"
        searchPlaceholder="Receipt number or customer"
        dropdowns={[
          { key: 'status', label: 'Status', options: STATUS_WORDS, value: filters.status, onChange: (value) => params.set({ status: value }) },
          { key: 'method', label: 'Payment method', options: METHOD_OPTIONS, value: filters.method, onChange: (value) => params.set({ method: value }) },
        ]}
        hasFilters={params.hasFilters}
        onClear={params.clear}
      />
      <Table
        caption="Sales, newest first"
        columns={columns}
        rows={pageRows}
        loading={view === 'loading'}
        error={view === 'error'}
        onRetry={() => params.set({ view: '' })}
        empty={emptyState}
        selectedKey={open ? open.id : undefined}
        onRowOpen={(sale) => openSale(sale.id)}
      />
      {view === 'data' || view === 'empty' ? (
        <Pagination page={current} size={size} total={shownRows.length} onPage={(next) => params.set({ page: next })} onSize={(next) => params.set({ size: next })} />
      ) : null}
    </div>
  );

  const detail = open ? (
    <DetailPanel
      title={`Sale ${open.id}`}
      status={<StatusLabel status={open.status} />}
      position={`${openIndex + 1} of ${pageRows.length} on this page`}
      onClose={() => params.set({ open: '', page: current })}
      onPrevious={openIndex > 0 ? () => openSale(pageRows[openIndex - 1].id) : undefined}
      onNext={openIndex < pageRows.length - 1 ? () => openSale(pageRows[openIndex + 1].id) : undefined}
      primary={{ label: 'Print receipt', onClick: () => {} }}
      secondary={[
        { label: 'Take payment', onClick: () => {} },
        { label: 'Return items', onClick: () => {} },
        { label: 'Void sale', variant: 'danger', onClick: () => {} },
      ]}
      details={[
        { label: 'Sales invoice', value: `ACC-PSINV-2026-${String(open.id).padStart(5, '0')}` },
        { label: 'Till session', value: 'POS-OPE-2026-00010' },
      ]}
    >
      <DetailFacts
        facts={[
          { label: 'Customer', value: open.customer },
          { label: 'Paid by', value: <PaymentChip method={open.method} /> },
          { label: 'Amount', value: formatMoney(open.amount) },
          { label: 'Time', value: when(open) },
        ]}
      />
    </DetailPanel>
  ) : null;

  return (
    <div style={{ display: 'grid', gap: 'var(--space-4)' }}>
      <Tabs label="Sales views" tabs={tabs} value={tabKey} />
      <div style={{ display: 'flex', flexWrap: 'wrap', alignItems: 'center', gap: 'var(--space-3)' }}>
        <span className="nl-label">Show the list as</span>
        <Segmented size="small" label="Show the list as" options={VIEWS} value={view} onChange={(value) => params.set({ view: value, page: current })} />
      </div>
      <ListWithDetail list={list} detail={detail} />
      <ConfirmDialog
        open={Boolean(voiding)}
        title={voiding ? `Void sale ${voiding.id}?` : ''}
        message="In a real shop this cancels the sale and cannot be undone. Here it is a demo and nothing is saved."
        confirmLabel="Void sale"
        destructive
        onCancel={() => setVoiding(null)}
        onConfirm={() => {
          toast.success(`Sale ${voiding.id} voided (demo, nothing was changed)`);
          setVoiding(null);
        }}
      />
    </div>
  );
};

const DataDemo = () => (
  <>
    <Card title="List page: tabs, summary, filters, table, pagination and detail panel" subtitle="135 made-up sales. Choose a row to open its panel; the address changes with every choice, so a link opens the same view">
      <SalesDemo />
    </Card>

    <Card title="Skeleton and empty state" subtitle="Grey shapes appear only after 200 ms of loading; an empty list names the next action">
      <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fill, minmax(280px, 1fr))', gap: 'var(--space-5)' }}>
        <div style={{ display: 'grid', gap: 'var(--space-2)' }}>
          <Skeleton width="40%" />
          <Skeleton />
          <Skeleton width="75%" />
        </div>
        <EmptyState title="No customers yet" description="Add your first customer to track what they owe and what they buy." action={{ label: 'Add a customer', icon: 'plus', onClick: () => {} }} />
        <EmptyState icon="alert" tone="error" title="We could not load this" description="Check your connection and try again. Nothing was changed." action={{ label: 'Try again', onClick: () => {} }} />
      </div>
      <p style={{ margin: 'var(--space-4) 0 0', color: 'var(--muted)', fontSize: 'var(--caption-size)' }}>
        <Link to={BASE} className="nl-page-link" style={{ color: 'var(--brand-text)' }}>Reset the list above</Link>
      </p>
    </Card>
  </>
);

export default DataDemo;
